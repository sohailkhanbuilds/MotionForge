"""Generate Blender-side import scripts for MotionForge BVH takes.

Blender is an optional external runtime. This module only writes a script;
it never imports bpy in the MotionForge Python environment.
"""
from __future__ import annotations

import json
from pathlib import Path


_SUPPORTED_CHARACTER_SUFFIXES = {".fbx", ".glb", ".gltf"}


def generate_blender_import_script(
    bvh_path: str | Path,
    blend_output: str | Path,
    character_path: str | Path | None = None,
    target_armature: str | None = None,
    bone_map_path: str | Path | None = None,
) -> str:
    """Return a standalone Blender Python script for importing a BVH take.

    If a character is supplied, it is imported as a separate asset. Animation
    is assigned only when target_armature names an armature whose pose-bone
    names cover every animated bone in the imported BVH action.
    """
    bvh = Path(bvh_path).expanduser()
    blend = Path(blend_output).expanduser()
    if bvh.suffix.lower() != ".bvh":
        raise ValueError("Motion input must be a .bvh file.")
    if not bvh.name:
        raise ValueError("A BVH input path is required.")
    character = None
    if character_path is not None:
        character = Path(character_path).expanduser()
        if character.suffix.lower() not in _SUPPORTED_CHARACTER_SUFFIXES:
            allowed = ", ".join(sorted(_SUPPORTED_CHARACTER_SUFFIXES))
            raise ValueError(f"Character must be one of: {allowed}.")
    if target_armature and character is None:
        raise ValueError("target_armature requires character_path.")
    bone_map = None
    if bone_map_path is not None:
        bone_map = Path(bone_map_path).expanduser()
        if bone_map.suffix.lower() != ".json":
            raise ValueError("Bone map must be a .json file.")
        if character is None or target_armature is None:
            raise ValueError("bone_map_path requires both character_path and target_armature.")

    config = {
        "bvh_path": str(bvh.resolve()),
        "blend_output": str(blend.resolve()),
        "character_path": str(character.resolve()) if character else None,
        "target_armature": target_armature,
        "bone_map_path": str(bone_map.resolve()) if bone_map else None,
    }
    encoded = json.dumps(config, ensure_ascii=True)
    return '''"""Generated by MotionForge. Run with Blender in background or UI mode."""
import bpy
import json
import os
import re

CONFIG = json.loads(''' + repr(encoded) + ''')


def import_character(path):
    suffix = os.path.splitext(path)[1].lower()
    before = set(bpy.data.objects)
    if suffix == ".fbx":
        bpy.ops.import_scene.fbx(filepath=path)
    elif suffix in (".glb", ".gltf"):
        bpy.ops.import_scene.gltf(filepath=path)
    else:
        raise RuntimeError("Unsupported character format: " + suffix)
    return [obj for obj in bpy.data.objects if obj not in before]


def animated_bone_names(action):
    names = set()
    if action is None:
        return names
    for curve in action.fcurves:
        match = re.search(r'pose\\.bones\\["([^"]+)"\\]', curve.data_path)
        if match:
            names.add(match.group(1))
    return names


def main():
    if not os.path.isfile(CONFIG["bvh_path"]):
        raise FileNotFoundError("BVH file not found: " + CONFIG["bvh_path"])

    objects_before_bvh_import = set(bpy.data.objects)
    bpy.ops.import_anim.bvh(filepath=CONFIG["bvh_path"])
    imported_armatures = [
        obj for obj in bpy.data.objects
        if obj not in objects_before_bvh_import and obj.type == "ARMATURE"
    ]
    if not imported_armatures:
        raise RuntimeError("Blender imported the BVH but no animated armature was found.")

    source = imported_armatures[-1]
    source.name = "MotionForge_BVH_Source"
    source_action = source.animation_data.action if source.animation_data else None
    if source_action:
        source_action.name = "MotionForge_Imported_Motion"

    character_objects = []
    if CONFIG["character_path"]:
        if not os.path.isfile(CONFIG["character_path"]):
            raise FileNotFoundError("Character file not found: " + CONFIG["character_path"])
        character_objects = import_character(CONFIG["character_path"])

    target_name = CONFIG["target_armature"]
    if target_name:
        target = bpy.data.objects.get(target_name)
        if target is None or target.type != "ARMATURE":
            raise RuntimeError("Target armature not found: " + target_name)

        if CONFIG["bone_map_path"]:
            with open(CONFIG["bone_map_path"], "r", encoding="utf-8") as handle:
                bone_map = json.load(handle)
            if not isinstance(bone_map, dict) or not bone_map:
                raise RuntimeError("Bone map JSON must be a non-empty source-to-target object.")
        else:
            bone_map = {
                name: name for name in animated_bone_names(source_action)
                if name in target.data.bones
            }

        invalid = [
            source_name + " -> " + str(target_name)
            for source_name, target_name in bone_map.items()
            if source_name not in source.pose.bones or target_name not in target.pose.bones
        ]
        if invalid:
            raise RuntimeError("Bone map contains unknown bones: " + ", ".join(invalid))
        if not bone_map:
            raise RuntimeError("No source-to-target bone pairs could be resolved.")

        # Bake mapped local pose channels into a new target action. This is a
        # name-mapped local-channel transfer, not rest-pose-aware retargeting.
        target.animation_data_create()
        target_action = bpy.data.actions.new("MotionForge_Mapped_Retarget")
        target.animation_data.action = target_action
        scene = bpy.context.scene
        start = int(source_action.frame_range[0]) if source_action else 1
        end = int(source_action.frame_range[1]) if source_action else 1
        for frame in range(start, end + 1):
            scene.frame_set(frame)
            for source_name, target_bone_name in bone_map.items():
                source_bone = source.pose.bones[source_name]
                target_bone = target.pose.bones[target_bone_name]
                target_bone.rotation_mode = "QUATERNION"
                target_bone.rotation_quaternion = source_bone.rotation_quaternion.copy()
                target_bone.keyframe_insert(data_path="rotation_quaternion", frame=frame)
                if source_bone.parent is None:
                    target_bone.location = source_bone.location.copy()
                    target_bone.keyframe_insert(data_path="location", frame=frame)
        print(
            "MotionForge mapped local channels:",
            len(bone_map), "bones on", target.name,
            "frames", start, "to", end
        )
        print(
            "WARNING: no rest-pose, bone-axis, scale or IK correction is applied; "
            "inspect the result before use."
        )
    elif character_objects:
        print(
            "Character imported, but animation was NOT auto-assigned. "
            "Set --target-armature to an armature name with matching bone names."
        )

    scene = bpy.context.scene
    scene.frame_start = 1
    scene.frame_end = max(1, int(source_action.frame_range[1]) if source_action else 1)
    scene.frame_set(scene.frame_start)
    output = CONFIG["blend_output"]
    os.makedirs(os.path.dirname(output) or ".", exist_ok=True)
    bpy.ops.wm.save_as_mainfile(filepath=output)
    print("MotionForge Blender scene saved:", output)
    print("Imported BVH armature:", source.name)
    print("Imported character objects:", len(character_objects))


if __name__ == "__main__":
    main()
'''


def write_blender_import_script(
    bvh_path: str | Path,
    script_path: str | Path,
    blend_output: str | Path,
    character_path: str | Path | None = None,
    target_armature: str | None = None,
    bone_map_path: str | Path | None = None,
) -> Path:
    """Write the generated Blender script and return its path."""
    destination = Path(script_path).expanduser()
    destination.parent.mkdir(parents=True, exist_ok=True)
    script = generate_blender_import_script(
        bvh_path=bvh_path,
        blend_output=blend_output,
        character_path=character_path,
        target_armature=target_armature,
        bone_map_path=bone_map_path,
    )
    destination.write_text(script, encoding="utf-8")
    return destination
